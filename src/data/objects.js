// The `materials` field above is a descriptive, human-readable list (good for display)
// but each object phrases it differently ("leather" vs "leather cushions" vs "leather or
// pony hide"), which makes it useless as a filter facet. MATERIAL_TAGS maps those free-form
// descriptions onto a small controlled vocabulary for filtering, mirroring the broad
// material categories (wood, metal, glass, fabric, plastic...) requested for the Archive filters.
const MATERIAL_TAG_RULES = [
  ["marble", /marble/i],
  ["glass", /glass/i],
  ["leather", /leather|hide/i],
  ["plastic", /plastic|\babs\b|polycarbonate|polystyrene|polyurethane/i],
  ["metal", /steel|aluminum|aluminium|chrome|\biron\b|wire|ball joints/i],
  ["cane", /\bcane\b/i],
  ["wood", /wood|walnut|plywood|hardwood|bamboo|washi/i],
  ["fabric", /fabric|canvas|jersey|vinyl|cord|foam|upholstery/i],
];

export const MATERIALS = ["wood", "metal", "glass", "fabric", "leather", "plastic", "marble", "cane"];

OBJECTS.forEach((object) => {
  const tags = new Set();
  object.materials.forEach((material) => {
    MATERIAL_TAG_RULES.forEach(([tag, pattern]) => {
      if (pattern.test(material)) tags.add(tag);
    });
  });
  object.materialTags = MATERIALS.filter((tag) => tags.has(tag));
  // A maker's cut-out photo (the piece alone on a plain ground): { ground, box } — cards show the
  // piece whole, on that ground (see SmartImage).
  const cutout = OBJECT_PHOTOS[object.id]?.cutout;
  if (cutout) object.cutout = cutout;
});
