// Pieces older than 1900 are few and scattered across centuries, so they share one bucket;
// from 1900 on every decade gets its own filter, labelled by its first year (1910, 1990, 2010…).
export const BEFORE_1900 = "before-1900";

export function decadeOf(year) {
  return year < 1900 ? BEFORE_1900 : Math.floor(year / 10) * 10;
}

const decadeValues = new Set(OBJECTS.map((o) => decadeOf(o.year)));
export const DECADES = [
  ...(decadeValues.has(BEFORE_1900) ? [BEFORE_1900] : []),
  ...[...decadeValues].filter((d) => d !== BEFORE_1900).sort((a, b) => a - b),
];

