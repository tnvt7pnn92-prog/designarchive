export function publishedStories(today) {
  return STORIES.filter((s) => s.date <= today).sort((a, b) => b.date.localeCompare(a.date));
}

// Today's scheduled story if there is one; otherwise a published story picked by the date,
// so the headline still changes every day once the queue runs out.
export function storyOfTheDay(today) {
  const published = publishedStories(today);
  return published.find((s) => s.date === today) ?? published[dayNumber(today) % published.length];
}

export function nextStory(today) {
  return STORIES.filter((s) => s.date > today).sort((a, b) => a.date.localeCompare(b.date))[0] ?? null;
}
