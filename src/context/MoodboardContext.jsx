import { createContext, useContext, useMemo, useReducer, useEffect, useCallback, useRef, useState } from "react";
import { boardSize, createPhoto, uid } from "../lib/moodboard.js";
import { activeBoard, moodboardsStore, saveActiveContent } from "../lib/moodboards.js";

const MoodboardContext = createContext(null);

const HISTORY_LIMIT = 100;
// Consecutive updates sharing a coalesce key (colour picker drags, keyboard nudges…)
// within this window collapse into a single undo step.
const COALESCE_MS = 1000;

function sameValue(a, b) {
  if (Array.isArray(a) && Array.isArray(b)) return a.length === b.length && a.every((v, i) => v === b[i]);
  return a === b;
}

// Recipes run inside the reducer, so they must stay pure: ids and random values are
// generated by the callers and passed in.
function reducer(state, action) {
  switch (action.type) {
    case "commit": {
      const next = action.recipe(state.elements);
      if (next === state.elements) return state;
      const merge =
        action.coalesce && state.coalesce?.key === action.coalesce && action.time - state.coalesce.time < COALESCE_MS;
      return {
        ...state,
        elements: next,
        past: merge ? state.past : [...state.past, state.elements].slice(-HISTORY_LIMIT),
        future: [],
        coalesce: action.coalesce ? { key: action.coalesce, time: action.time } : null,
      };
    }
    case "undo":
      if (!state.past.length) return state;
      return {
        ...state,
        elements: state.past[state.past.length - 1],
        past: state.past.slice(0, -1),
        future: [state.elements, ...state.future],
        coalesce: null,
      };
    case "redo":
      if (!state.future.length) return state;
      return {
        ...state,
        elements: state.future[0],
        past: [...state.past, state.elements],
        future: state.future.slice(1),
        coalesce: null,
      };
    case "background":
      return state.background === action.value ? state : { ...state, background: action.value };
    // The sheet's details: title block and real-scale room width (not part of the undo history).
    case "sheet":
      return { ...state, sheet: { ...state.sheet, ...action.patch } };
    // Another board was opened, or the account brought a newer version of this one.
    case "load":
      return stateFor(action.board);
    default:
      return state;
  }
}

function stateFor(board) {
  return {
    boardId: board.id,
    elements: board.elements,
    background: board.background,
    sheet: { format: board.format, cartouche: board.cartouche, roomWidth: board.roomWidth },
    past: [],
    future: [],
    coalesce: null,
  };
}

function initState() {
  return stateFor(activeBoard());
}

// The editor works on the active board of lib/moodboards.js: it loads it, writes every change
// back to it, and reloads when another board is opened or the account sends a newer version.
export function MoodboardProvider({ children }) {
  const [state, dispatch] = useReducer(reducer, undefined, initState);
  const { elements, background, boardId, sheet } = state;
  const [saveFailed, setSaveFailed] = useState(false);
  // The date stamp of the editor's own last write, to tell it apart from changes made elsewhere.
  const written = useRef(null);
  const current = useRef(state);

  useEffect(() => {
    current.current = state;
  });

  useEffect(() => {
    const board = activeBoard();
    if (board.id !== boardId) return; // another board is being opened
    if (board.elements === elements && board.background === background && board.format === sheet.format && board.cartouche === sheet.cartouche && board.roomWidth === sheet.roomWidth) return;
    written.current = saveActiveContent(elements, background, sheet);
    setSaveFailed(moodboardsStore.saveFailed());
  }, [elements, background, sheet, boardId]);

  useEffect(
    () =>
      moodboardsStore.subscribe(() => {
        const board = activeBoard();
        const open = current.current;
        const switched = board.id !== open.boardId;
        const replaced = board.updatedAt !== written.current && board.elements !== open.elements;
        if (switched || replaced) dispatch({ type: "load", board });
      }),
    []
  );

  const commit = useCallback((recipe, coalesce) => {
    dispatch({ type: "commit", recipe, coalesce, time: Date.now() });
  }, []);

  const setBackground = useCallback((value) => dispatch({ type: "background", value }), []);
  const setSheet = useCallback((patch) => dispatch({ type: "sheet", patch }), []);

  const addElement = useCallback(
    (element) => {
      commit((els) => [...els, element]);
      return element.id;
    },
    [commit]
  );

  const updateElement = useCallback(
    (id, patch, { coalesce } = {}) => {
      commit((els) => {
        const index = els.findIndex((el) => el.id === id);
        if (index === -1) return els;
        const current = els[index];
        if (Object.keys(patch).every((key) => sameValue(current[key], patch[key]))) return els;
        const next = [...els];
        next[index] = { ...current, ...patch };
        return next;
      }, coalesce && `${coalesce}:${id}`);
    },
    [commit]
  );

  const removeElement = useCallback(
    (id) => {
      commit((els) => (els.some((el) => el.id === id) ? els.filter((el) => el.id !== id) : els));
    },
    [commit]
  );

  const duplicateElement = useCallback(
    (id) => {
      const copyId = uid();
      commit((els) => {
        const source = els.find((el) => el.id === id);
        if (!source) return els;
        return [...els, { ...source, id: copyId, x: source.x + 24, y: source.y + 24 }];
      });
      return copyId;
    },
    [commit]
  );

  // direction: "forward" | "backward" | "front" | "back"
  const reorderElement = useCallback(
    (id, direction) => {
      commit((els) => {
        const index = els.findIndex((el) => el.id === id);
        if (index === -1) return els;
        const target = {
          forward: Math.min(els.length - 1, index + 1),
          backward: Math.max(0, index - 1),
          front: els.length - 1,
          back: 0,
        }[direction];
        if (target === undefined || target === index) return els;
        const next = [...els];
        const [moved] = next.splice(index, 1);
        next.splice(target, 0, moved);
        return next;
      });
    },
    [commit]
  );

  // An empty board started from a template or the collection: its elements (one undo step),
  // ground and format.
  const startFrom = useCallback(
    (content) => {
      commit(() => content.elements);
      dispatch({ type: "background", value: content.background ?? "paper" });
      dispatch({ type: "sheet", patch: { format: content.format } });
    },
    [commit]
  );

  const clear = useCallback(() => {
    commit((els) => (els.length ? [] : els));
  }, [commit]);

  const undo = useCallback(() => dispatch({ type: "undo" }), []);
  const redo = useCallback(() => dispatch({ type: "redo" }), []);

  /* Archive pieces — the API used by ObjectCard stays the same. */

  const items = useMemo(
    () => elements.filter((el) => el.type === "photo").map((el) => ({ id: el.objectId, elementId: el.id })),
    [elements]
  );
  const itemIds = useMemo(() => new Set(items.map((it) => it.id)), [items]);
  const isInMoodboard = useCallback((objectId) => itemIds.has(objectId), [itemIds]);

  const addItem = useCallback(
    (object) => {
      const id = uid();
      const jitter = { x: Math.random() * 20 - 10, y: Math.random() * 20 - 10, rotation: Math.random() * 8 - 4 };
      commit((els) => {
        if (els.some((el) => el.type === "photo" && el.objectId === object.id)) return els;
        const n = els.filter((el) => el.type === "photo").length;
        return [...els, { ...createPhoto(object.id, n, jitter, boardSize(current.current.sheet.format)), id }];
      });
    },
    [commit]
  );

  const removeItem = useCallback(
    (objectId) => {
      commit((els) =>
        els.some((el) => el.type === "photo" && el.objectId === objectId)
          ? els.filter((el) => !(el.type === "photo" && el.objectId === objectId))
          : els
      );
    },
    [commit]
  );

  const toggleItem = useCallback(
    (object) => (isInMoodboard(object.id) ? removeItem(object.id) : addItem(object)),
    [isInMoodboard, addItem, removeItem]
  );

  const value = useMemo(
    () => ({
      elements,
      background,
      setBackground,
      sheet,
      setSheet,
      saveFailed,
      boardId,
      addElement,
      updateElement,
      removeElement,
      duplicateElement,
      reorderElement,
      clear,
      startFrom,
      undo,
      redo,
      canUndo: state.past.length > 0,
      canRedo: state.future.length > 0,
      items,
      addItem,
      removeItem,
      toggleItem,
      isInMoodboard,
    }),
    [
      elements,
      background,
      setBackground,
      sheet,
      setSheet,
      saveFailed,
      boardId,
      addElement,
      updateElement,
      removeElement,
      duplicateElement,
      reorderElement,
      clear,
      startFrom,
      undo,
      redo,
      state.past.length,
      state.future.length,
      items,
      addItem,
      removeItem,
      toggleItem,
      isInMoodboard,
    ]
  );

  return <MoodboardContext.Provider value={value}>{children}</MoodboardContext.Provider>;
}

export function useMoodboard() {
  const ctx = useContext(MoodboardContext);
  if (!ctx) throw new Error("useMoodboard must be used within a MoodboardProvider");
  return ctx;
}
