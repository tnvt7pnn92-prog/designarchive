// Generates src/data/homeData.js: everything the landing page shows, and nothing else.
//
// Importing the catalogue on the home page costs 150 kB gzipped for a handful of names and
// thumbnails, and the home page is where visitors from social media land. This script bakes that
// handful into a small module instead. It runs from `npm run build` (prebuild), so it can never
// go stale.
import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const load = (rel) => import(pathToFileURL(path.join(root, rel)).href);

const { OBJECTS } = await load("src/data/objects.js");
const { BY_DESIGNER } = await load("src/data/indexes.js");
const { ICONIC_PIECES, FAMOUS_PIECES } = await load("src/data/iconicPieces.js");
const { cardImage } = await load("src/data/objectPhotos.js");
const { isCardSafe } = await load("src/data/photoLicence.js");
const { MARKETS } = await load("src/data/markets.js");
const { countryOf } = await load("src/lib/marketPlaces.js");
const { publishedStories } = await load("src/data/stories.js");
const { dateKey } = await load("src/lib/today.js");

// What a card and its museum label need, and nothing more.
const card = (o) => ({
  id: o.id,
  name: o.name,
  designer: o.designer,
  brand: o.brand,
  year: o.year,
  country: o.country,
  category: o.category,
  materialTags: o.materialTags,
  image: o.image,
  thumb: cardImage(o.image),
  ...(o.cutout ? { cutout: o.cutout } : null),
});

const byId = new Map(OBJECTS.map((o) => [o.id, o]));
const need = (id) => {
  const o = byId.get(id);
  if (!o) throw new Error(`build-home-data: no piece "${id}"`);
  return o;
};

// The gold ribbon under the hero: the most famous pieces, name and year.
const RIBBON = FAMOUS_PIECES.slice(0, 16).map((id) => {
  const o = need(id);
  return { id, name: o.name.replace(/\s*\(.*\)$/, ""), year: o.year };
});

// The hero's orbit: makers' cut-out photos (shown whole on their own ground), turning in 3D. Light
// files only (all six together weigh about 270 kB), so the ring turns smoothly from the start.
const ORBIT = ["lc1-chair", "atollo-lamp", "elda-chair", "toio-lamp", "il-conico-kettle", "mariposa-sofa"].map((id) => {
  const o = need(id);
  if (!o.cutout) throw new Error(`build-home-data: the orbit's "${id}" needs a maker's cut-out photo`);
  return card(o);
});

// The time machine: four famous pieces per decade, 1920s to 1980s, in the order of their year.
const DECADES = [1920, 1930, 1950, 1960, 1970, 1980];
const showable = (id) => isCardSafe(id) || Boolean(byId.get(id)?.cutout);
const TIME = DECADES.flatMap((decade) => {
  const inDecade = (o) => o.year >= decade && o.year < decade + 10;
  const famous = FAMOUS_PIECES.filter((id) => byId.has(id) && inDecade(byId.get(id)) && showable(id));
  const more = OBJECTS.filter((o) => inDecade(o) && isCardSafe(o.id) && !famous.includes(o.id)).map((o) => o.id);
  return [...famous, ...more].slice(0, 4);
})
  .map((id) => card(need(id)))
  .sort((a, b) => a.year - b.year);

// The example collection shown to visitors without one: real pieces, invented states, and the
// page says so.
const COLLECTION_DEMO = [
  ["cesca-chair", "own"],
  ["ph5-lamp", "want"],
  ["acapulco-chair", "seen"],
  ["superleggera-chair", "own"],
];

const data = {
  STATS: {
    pieces: OBJECTS.length,
    designers: BY_DESIGNER.size,
    marketCountries: new Set(MARKETS.map(countryOf)).size,
    // Rebuilt every morning by the deploy, so the count follows the stories going live.
    stories: publishedStories(dateKey()).length,
  },
  RIBBON,
  ORBIT,
  TIME,
  COLLECTION_DEMO: COLLECTION_DEMO.map(([id, status]) => ({ ...card(need(id)), status })),
  // Just enough about every iconic piece (the 404 page shows one).
  ICONIC: Object.fromEntries(
    ICONIC_PIECES.map((id) => [id, { name: byId.get(id).name, image: byId.get(id).image, ...(byId.get(id).cutout ? { cutout: byId.get(id).cutout } : null) }])
  ),
};
const body = Object.entries(data)
  .map(([key, value]) => `export const ${key} = ${JSON.stringify(value, null, 2)};`)
  .join("\n\n");

writeFileSync(
  path.join(root, "src/data/homeData.js"),
  `// GENERATED by scripts/build-home-data.mjs — do not edit. Regenerated on every build.\n// It exists so the landing page does not have to load the whole catalogue.\n\n${body}\n`
);

// Story covers point at archive pieces, and so do the pieces each story names (`related`, shown
// as pinned photos on the stories page); story cards appear on the home page too, so they get the
// same treatment: a tiny map from piece id to the photo, instead of the catalogue.
const { STORIES } = await load("src/data/stories.js");
const coverIds = [...new Set(STORIES.flatMap((s) => [s.cover?.object, ...(s.related ?? [])]).filter(Boolean))];
const covers = Object.fromEntries(
  coverIds.filter((id) => byId.has(id)).map((id) => {
    const o = byId.get(id);
    return [
      id,
      { name: o.name, designer: o.designer, year: o.year, country: o.country, image: o.image, category: o.category, materialTags: o.materialTags, ...(o.cutout ? { cutout: o.cutout } : null) },
    ];
  })
);
writeFileSync(
  path.join(root, "src/data/storyCovers.js"),
  `// GENERATED by scripts/build-home-data.mjs — do not edit. Regenerated on every build.\n// The photo behind each story cover, so a story card never needs the whole catalogue.\n\nexport const STORY_COVERS = ${JSON.stringify(covers, null, 2)};\n`
);

const bytes = Buffer.byteLength(body, "utf8");
console.log(`home data: ${OBJECTS.length} pieces → ${(bytes / 1024).toFixed(1)} kB (${Object.keys(data.ICONIC).length} iconic pieces)`);
